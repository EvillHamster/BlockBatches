SET XACT_ABORT ON;
BEGIN TRANSACTION;
IF EXISTS(SELECT 1 FROM sys.check_constraints WHERE parent_object_id=OBJECT_ID(N'dbo.Users') AND name=N'CK_Users_role' AND definition NOT LIKE N'%ENGINEER%')
BEGIN
 ALTER TABLE dbo.Users DROP CONSTRAINT CK_Users_role;
 ALTER TABLE dbo.Users WITH CHECK ADD CONSTRAINT CK_Users_role CHECK(role IN ('KEYUSER','QUALITY','ADMIN','EMPLOYER','ENGINEER'));
END;
COMMIT TRANSACTION;
